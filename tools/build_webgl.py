def run_prepare(project: str, unity_dir: str | None = None) -> None:
    """步骤 1：工程后处理（断循环引用 + 生成 manifest + 隔离插件）。"""
    here = os.path.dirname(os.path.abspath(__file__))

    # 1a) 断开「资源 -> 场景对象」反向引用
    #     否则 Unity 导入时刷 Do not use ReadObjectThreaded on scene objects! 并最终段错误
    fix = os.path.join(here, "fix_circular_refs.py")
    if os.path.isfile(fix):
        print("[1a] 断开循环引用 ------------------------------")
        env = dict(os.environ, GTW_PROJECT=project)
        subprocess.run([sys.executable, fix, "--apply"], check=False, env=env)
    else:
        print("[!] 未找到 fix_circular_refs.py，跳过")

    # 1b) manifest + 插件隔离
    prep = os.path.join(here, "prepare_unity_project.py")
    if not os.path.isfile(prep):
        print("[!] 未找到 prepare_unity_project.py，跳过")
        return
    print("[1b] 工程后处理 ------------------------------")
    cmd = [sys.executable, prep, "--project", project]
    if unity_dir:
        cmd += ["--unity-dir", unity_dir]
    subprocess.run(cmd, check=False)


def exclude_windows_addressables(project: str) -> None:
    """
    把 Assets/StreamingAssets/aa 移出工程。

    那是 AssetRipper 从游戏包里挖出来的 **StandaloneWindows64** Addressables bundle（约 4GB），
    原样留着会被塞进 WebGL 产物；WebGL 的 bundle 需要重新构建（见 GTWWebGL.PerformFullBuild）。
    """
    src = os.path.join(project, "Assets", "StreamingAssets", "aa")
    if not os.path.isdir(src):
        return
    dst = os.path.join(os.path.dirname(project.rstrip("\\/")), "aa_win_backup", "aa")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst):
        print("[*] 备份已存在，跳过移动:", dst)
        return
    print("[*] 移出 Windows 版 Addressables:", src, "->", dst)
    shutil.move(src, dst)


