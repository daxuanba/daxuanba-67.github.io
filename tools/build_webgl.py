"""
Get To Work · WebGL 一键构建脚本
--------------------------------
把 AssetRipper 导出的工程，用 Unity 6000.0.35f1 重新编译成浏览器可跑版本，
产物 + build.json 落到 game/build/（分片打包交给 split_package.py）。

用法：
  python tools/build_webgl.py \
      --project "D:/GetToWorkUnity/ExportedProject" \
      --out "../../game/build" \
      [--unity "D:/Unity/6000.0.35f1/Editor/Unity.exe"] \
      [--skip-prepare]

流程：
  1. fix_circular_refs.py    —— 断开「资源 -> 场景对象」反向引用（否则导入死循环 + 段错误）
  2. prepare_unity_project.py —— 生成 manifest.json / 隔离包 DLL 与 Windows 专属原生插件
  3. 移出 Assets/StreamingAssets/aa（4GB 的 StandaloneWindows64 bundle，不能进 WebGL 产物）
  4. 注入 Assets/Editor/GTWWebGL.cs + Assets/csc.rsp → Unity 批处理打包
  5. 收集产物 → build.json

已知必需的两个补丁（都已在脚本里自动处理，改动别丢）：
  * 编译宏 ENABLE_UNITY_COLLECTIONS_CHECKS
      com.unity.collections 2.5.1 的 NativeList.AsReadOnly 在未定义该宏时调用 2 参数
      NativeArray<T>.ReadOnly 构造，而引擎只暴露 3 参数版本 -> CS7036。
  * Assets/csc.rsp 显式 -r UnityEngine.dll
      DOTween.dll 引用旧 UnityEngine facade，WebGL 播放器编译期不给该引用
      -> MovingObject.cs CS0012（Vector3/Quaternion 找不到程序集）。
"""
