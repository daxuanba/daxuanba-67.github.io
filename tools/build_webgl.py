def run_unity(unity_exe: str, project: str, log_path: str, unity_dir: str, method: str) -> int:
    """步骤 2：注入构建脚本 + 命令行构建。"""
    here = os.path.dirname(os.path.abspath(__file__))
    editor_dir = os.path.join(project, "Assets", "Editor")
    os.makedirs(editor_dir, exist_ok=True)

    # 2a) 注入构建脚本（仓库 tools/unity_editor/GTWWebGL.cs 为准）
    src_editor = os.path.join(here, "unity_editor", "GTWWebGL.cs")
    if not os.path.isfile(src_editor):
        raise RuntimeError("缺少 tools/unity_editor/GTWWebGL.cs")
    shutil.copy2(src_editor, os.path.join(editor_dir, "GTWWebGL.cs"))

    # 注意：历史上曾用 Assets/csc.rsp 追加 `-r UnityEngine.dll` 试图修 DOTween 的 CS0012，
    # 但实测会让 UnityLinker 找不到 UnityEngine.SharedInternalsModule 而崩。
    # MovingObject.cs 已改为纯协程（不再依赖 DOTween），所以这里**不再写 csc.rsp**。
    # 若项目里残留了 csc.rsp，删掉它，否则 WebGL 链接阶段必崩。
    rsp = os.path.join(project, "Assets", "csc.rsp")
    if os.path.isfile(rsp):
        os.remove(rsp)
        print("[*] 删除残留 csc.rsp:", rsp)

    # Unity 的 WebGL 构建会调用 node（uglify / emscripten）。若环境里残留
    # NODE_OPTIONS / ELECTRON_RUN_AS_NODE（例如被其它 IDE 注入），会劫持 node 导致崩溃，
    # 这里显式清掉这两个变量。
    safe_env = dict(os.environ)
    safe_env.pop("NODE_OPTIONS", None)
    safe_env.pop("ELECTRON_RUN_AS_NODE", None)

    cmd = [
        unity_exe, "-batchmode", "-quit", "-nographics", "-accept-apiupdate",
        "-projectPath", project,
        "-executeMethod", method,
        "-buildTarget", "WebGL",
        "-logFile", log_path,
    ]
    print("[2] Unity 构建 ------------------------------")
    print("     ", " ".join(cmd))
    t0 = time.time()
    proc = subprocess.run(cmd, env=safe_env)
    print("[*] Unity 退出码: %s  耗时 %.1f 分钟" % (proc.returncode, (time.time() - t0) / 60))
    return proc.returncode


def collect_build(src_build_dir: str, out_dir: str, company: str, product: str) -> dict:
    """步骤 3：收集产物并生成 build.json。"""
    print("[3/3] 收集产物 ------------------------------")
    os.makedirs(out_dir, exist_ok=True)
    for name in os.listdir(src_build_dir):
        s = os.path.join(src_build_dir, name)
        d = os.path.join(out_dir, name)
        if os.path.isdir(s):
            if os.path.exists(d):
                shutil.rmtree(d)
            shutil.copytree(s, d)
        else:
            shutil.copy2(s, d)

    build_sub = os.path.join(out_dir, "Build")
    if not os.path.isdir(build_sub):
        build_sub = out_dir

    def find(ext):
        # 优先 Unity 压缩变体（WebGL.data.unityweb 等），loader.js 内置解压
        for f in sorted(os.listdir(build_sub)):
            if f.lower().endswith(ext.lower() + ".unityweb"):
                return f
        for f in sorted(os.listdir(build_sub)):
            if f.lower().endswith(ext.lower()):
                return f
        return None

    loader, data, framework, code = (
        find(".loader.js"), find(".data"), find(".framework.js"), find(".wasm"),
    )
    missing = [n for n, v in
               (("loader.js", loader), (".data", data),
                (".framework.js", framework), (".wasm", code)) if not v]
    if missing:
        raise RuntimeError("构建产物不完整，缺少: %s（见 Unity 日志）" % ", ".join(missing))

    cfg = {
        "loaderUrl": "build/" + loader,
        "dataUrl": "build/" + data,
        "frameworkUrl": "build/" + framework,
        "codeUrl": "build/" + code,
        "streamingAssetsUrl": "build/StreamingAssets",
        "companyName": company,
        "productName": product,
        "webglContextAttributes": CONTEXT_ATTRS,
    }
    with open(os.path.join(out_dir, "build.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)
    print(json.dumps(cfg, ensure_ascii=False, indent=2))
    return cfg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--unity", default=DEFAULT_UNITY, help="Unity Editor 路径")
    ap.add_argument("--project", required=True, help="AssetRipper 导出的工程根")
    ap.add_argument("--out", default="game/build", help="WebGL 产物输出目录")
    ap.add_argument("--company", default="DaXuanBa")
    ap.add_argument("--product", default="Get To Work")
    ap.add_argument("--skip-prepare", action="store_true")
    ap.add_argument("--skip-unity", action="store_true", help="只做收集（复用已有 Builds/WebGL）")
    ap.add_argument("--full", action="store_true",
                    help="同时重建 Addressables（关卡场景走 LoadSceneAsync，必须为此平台重打包）")
    args = ap.parse_args()

    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = args.out if os.path.isabs(args.out) else os.path.join(repo_root, args.out)
    log_path = os.path.join(args.project, "..", "logs", "webgl_build.log")
    log_path = os.path.abspath(log_path)
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    src_build = os.path.join(args.project, "Builds", "WebGL")

    # Unity 安装根目录（从 Unity.exe 反推：<dir>/Editor/Unity.exe）
    unity_dir = os.path.dirname(os.path.dirname(os.path.abspath(args.unity)))

    if not args.skip_prepare:
        run_prepare(args.project, unity_dir)

    exclude_windows_addressables(args.project)

    if not args.skip_unity:
        if not os.path.isfile(args.unity):
            print("[!] 找不到 Unity: %s" % args.unity)
            sys.exit(1)
        method = "GTWWebGL.PerformFullBuild" if args.full else "GTWWebGL.PerformBuild"
        if run_unity(args.unity, args.project, log_path, unity_dir, method) != 0:
            print("[!] Unity 构建失败，详见日志: %s" % log_path)
            sys.exit(1)

    if not os.path.isdir(src_build):
        print("[!] 未找到构建输出: %s" % src_build)
        sys.exit(1)

    collect_build(src_build, out_dir, args.company, args.product)
    print("[*] 完成 →", out_dir)
    print("[*] 下一步: python tools/split_package.py --build %s --site .." % out_dir)


if __name__ == "__main__":
    main()
